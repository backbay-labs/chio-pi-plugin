// Trusted maintenance generator. Downloads are never performed by the resource.
// Supply a directory containing the four exact, independently downloaded pins.
import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import {join} from "node:path";

const pins = {
  "CaseFolding.txt": ["https://www.unicode.org/Public/15.1.0/ucd/CaseFolding.txt", "4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf"],
  "UnicodeData.txt": ["https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt", "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86"],
  "DerivedCoreProperties.txt": ["https://www.unicode.org/Public/15.1.0/ucd/DerivedCoreProperties.txt", "f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b"],
  "LICENSE.txt": ["https://www.unicode.org/license.txt", "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"],
};
assert.ok(process.argv[2], "Pass the downloaded pinned-data directory");
const sources = {};
for (const [name, [, digest]] of Object.entries(pins)) {
  const bytes = await readFile(join(process.argv[2], name)); assert.equal(createHash("sha256").update(bytes).digest("hex"), digest, `${name} must match the official pinned bytes`); sources[name] = bytes.toString("utf8");
}
const visible = new Set(); let first;
for (const line of sources["UnicodeData.txt"].trim().split("\n")) {
  const [hex, name, category] = line.split(";"); const code = parseInt(hex, 16);
  if (name.endsWith(", First>")) {first = code; continue;}
  if (/^[LMNPS]/.test(category) || category === "Zs") for (let current = first ?? code; current <= code; current++) visible.add(current);
  first = undefined;
}
for (const line of sources["DerivedCoreProperties.txt"].split("\n")) {
  const [range, property] = line.split("#")[0].split(";").map(value => value.trim());
  if (property !== "Default_Ignorable_Code_Point") continue;
  const [start, end = start] = range.split("..").map(value => parseInt(value, 16)); for (let code = start; code <= end; code++) visible.delete(code);
}
const ranges = [];
for (const code of [...visible].sort((a, b) => a - b)) {
  if (ranges.length && ranges.at(-1) === code - 1) ranges[ranges.length - 1] = code;
  else ranges.push(code, code);
}
const folds = [];
for (const line of sources["CaseFolding.txt"].split("\n")) {
  const [hex, status, mapping] = line.split("#")[0].split(";").map(value => value.trim());
  if (status !== "C" && status !== "F") continue;
  folds.push([parseInt(hex, 16), String.fromCodePoint(...mapping.split(" ").map(value => parseInt(value, 16)))]);
}
const header = `/* Generated by test/helpers/generate-coding-unicode.mjs from official Unicode 15.1.0 data.\n * Never use runtime discovery, model callbacks or locale-dependent case mapping.\n *\n${Object.entries(pins).map(([name, [url, digest]]) => ` * ${name}: ${url}\n * SHA256: ${digest}`).join("\n")}\n * Unicode data copyright 2023 Unicode, Inc.\n *\n${sources["LICENSE.txt"].trimEnd().split("\n").map(line => line ? ` * ${line}` : " *").join("\n")}\n */\n`;
const wrappedRanges = Array.from({length: Math.ceil(ranges.length / 16)}, (_, index) => `  ${ranges.slice(index * 16, index * 16 + 16).map(value => `0x${value.toString(16)}`).join(", ")},`).join("\n");
const output = `${header}export const unicodeNamespaceVersion = "15.1.0";\n// ${visible.size} supported scalars in ${ranges.length / 2} inclusive ranges.\nexport const unicodeVisibleRanges: readonly number[] = Object.freeze([\n${wrappedRanges}\n]);\n// Default full case folding: C + F entries; Turkic T and simple S are excluded.\nexport const unicodeFullFoldEntries: readonly (readonly [number, string])[] = Object.freeze([\n${folds.map(([code, value]) => `  Object.freeze<[number, string]>([0x${code.toString(16)}, ${JSON.stringify(value)}]),`).join("\n")}\n]);\n`;
await writeFile(new URL("../../src/coding-resource/unicode-data.ts", import.meta.url), output);
console.log(JSON.stringify({version: "15.1.0", visibleScalars: visible.size, ranges: ranges.length / 2, fullFolds: folds.length, generatedBytes: Buffer.byteLength(output), generatedSha256: createHash("sha256").update(output).digest("hex")}));
